"""
ResourceShift AI - Proposal Management & Local Audit Trail
-----------------------------------------------------------
Maintains persistent, structured audit logs for action proposals, human approvals,
and rejections.

Security Invariants:
- All decisions require an identified actor ('approved_by' / 'rejected_by').
- Human approval registers acceptance for facility operational follow-up;
  it NEVER triggers direct physical actuation.
- Untrusted text notes are sanitized and stored as passive data.
"""

from __future__ import annotations

import datetime
import json
from pathlib import Path
from typing import Any, Dict, List, Optional
import uuid

DEFAULT_AUDIT_PATH = Path("data/audit_log.json")
DEFAULT_PROPOSALS_PATH = Path("data/proposals.json")

# In-memory stores with optional disk synchronization
_AUDIT_LOGS: List[Dict[str, Any]] = []
_PROPOSALS: Dict[str, Dict[str, Any]] = {}


def _ensure_data_dir(file_path: Path) -> None:
    file_path.parent.mkdir(parents=True, exist_ok=True)


def load_state(audit_path: Path = DEFAULT_AUDIT_PATH, proposals_path: Path = DEFAULT_PROPOSALS_PATH) -> None:
    """Loads existing audit logs and proposals from disk if available."""
    global _AUDIT_LOGS, _PROPOSALS
    if audit_path.exists():
        try:
            with open(audit_path, "r", encoding="utf-8") as f:
                _AUDIT_LOGS = json.load(f)
        except Exception:
            _AUDIT_LOGS = []

    if proposals_path.exists():
        try:
            with open(proposals_path, "r", encoding="utf-8") as f:
                _PROPOSALS = json.load(f)
        except Exception:
            _PROPOSALS = {}


def persist_state(audit_path: Path = DEFAULT_AUDIT_PATH, proposals_path: Path = DEFAULT_PROPOSALS_PATH) -> None:
    """Persists in-memory audit logs and proposals to JSON files."""
    try:
        _ensure_data_dir(audit_path)
        with open(audit_path, "w", encoding="utf-8") as f:
            json.dump(_AUDIT_LOGS, f, indent=2)
    except Exception:
        pass

    try:
        _ensure_data_dir(proposals_path)
        with open(proposals_path, "w", encoding="utf-8") as f:
            json.dump(_PROPOSALS, f, indent=2)
    except Exception:
        pass


def save_proposal(proposal: Dict[str, Any]) -> Dict[str, Any]:
    """
    Saves an advisory action proposal generated by the system/agent.
    Enforces that proposals are non-actuating and require human approval.
    """
    proposal_id = str(proposal.get("proposal_id", f"PROP-{uuid.uuid4().hex[:8].upper()}"))
    now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()

    record = {
        "proposal_id": proposal_id,
        "anomaly_id": str(proposal.get("anomaly_id", "UNKNOWN")),
        "resource_type": str(proposal.get("resource_type", "electricity")),
        "recommended_action": str(proposal.get("recommended_action", "")),
        "reason": str(proposal.get("reason", "")),
        "estimated_savings_usd": float(proposal.get("estimated_savings_usd", 0.0)),
        "estimated_co2_kg": float(proposal.get("estimated_co2_kg", 0.0)),
        "confidence_score": float(proposal.get("confidence_score", 0.90)),
        "status": "pending_review",
        "created_at": now_iso,
        "is_actuated": False,
        "requires_human_approval": True,
    }

    _PROPOSALS[proposal_id] = record
    persist_state()
    return record


def get_proposal(proposal_id: str) -> Optional[Dict[str, Any]]:
    """Retrieves a proposal by its ID."""
    return _PROPOSALS.get(proposal_id)


def list_proposals(status: Optional[str] = None) -> List[Dict[str, Any]]:
    """Lists stored proposals, optionally filtered by status."""
    proposals = list(_PROPOSALS.values())
    if status:
        proposals = [p for p in proposals if p.get("status") == status]
    return proposals


def record_action_decision(
    proposal_id: str,
    decision: str,  # 'approved' or 'rejected'
    actor: str,
    notes_or_reason: str = "",
    metadata: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Records an immutable audit event for human review decision.

    Args:
        proposal_id: Identifier of the proposal being evaluated.
        decision: 'approved' or 'rejected'.
        actor: Username or identifier of the facility manager.
        notes_or_reason: Human explanation or follow-up ticket notes.
        metadata: Optional additional contextual attributes.

    Returns:
        Structured audit record.

    Raises:
        ValueError: If actor is empty or decision is invalid.
    """
    if not actor or not actor.strip():
        raise ValueError("Decision actor (approved_by / rejected_by) must be specified.")
    if decision not in ("approved", "rejected"):
        raise ValueError(f"Decision must be 'approved' or 'rejected', got '{decision}'.")

    now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()
    audit_id = f"AUDIT-{uuid.uuid4().hex[:10].upper()}"

    # Update proposal status if proposal exists in memory
    if proposal_id in _PROPOSALS:
        _PROPOSALS[proposal_id]["status"] = decision
        _PROPOSALS[proposal_id]["decided_at"] = now_iso
        _PROPOSALS[proposal_id]["decided_by"] = actor.strip()

    audit_entry = {
        "audit_id": audit_id,
        "proposal_id": proposal_id,
        "decision": decision,
        "actor": actor.strip(),
        "notes_or_reason": str(notes_or_reason).strip(),
        "timestamp": now_iso,
        "metadata": metadata or {},
        "no_actuation_guarantee": True,
        "policy": "Human-in-the-Loop decision recorded. No autonomous actuators invoked.",
    }

    _AUDIT_LOGS.append(audit_entry)
    persist_state()
    return audit_entry


def get_audit_trail(proposal_id: Optional[str] = None) -> List[Dict[str, Any]]:
    """Returns the audit log, optionally filtered by proposal_id."""
    if proposal_id:
        return [entry for entry in _AUDIT_LOGS if entry.get("proposal_id") == proposal_id]
    return list(_AUDIT_LOGS)


def reset_audit_store() -> None:
    """Resets in-memory audit store (primarily for unit test isolation)."""
    global _AUDIT_LOGS, _PROPOSALS
    _AUDIT_LOGS = []
    _PROPOSALS = {}
